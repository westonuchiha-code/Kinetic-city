/* ---------- building a frame ---------- */
const OUTFIT = { Z: ['zip', 'T', 'C'], R: ['stripe', 'T', 'C'], r: ['stripe', 't', 'c'], q: ['badge', 'Q', 'C'], A: ['pads', 'T', 'C'], a: ['pads', 't', 'c'],
  U: ['cuffs', 'T', 'c'], u: ['cuffs', 't', 'd'], E: ['belt', 'b', 'd'], V: ['belt', 'Q', 'd'] };
function buildCharGrid(dir, frame, o) {
  if (o.glide) frame = 0;                                        // robed figures float: no walk frames
  const A = (o.big ? BIG_ART : CHAR_ART)[dir], up = frame === 1 || frame === 3 ? 1 : 0, oy = o.headroom || 0;   // headroom: extra rows above for tall hair
  const W0 = A.torso[0][0].length, hx = (W0 - CH_W) >> 1, bodyRows = A.torso[0].length, H0 = 13 + bodyRows + A.legs[0].length + oy;
  const g = Array.from({ length: H0 }, () => new Array(W0).fill('.'));
  const put = (rows, y0, x0) => rows.forEach((r, i) => { const y = y0 + i + oy; if (y >= 0 && y < H0) for (let x = 0; x < r.length; x++) if (r[x] !== '.') g[y][x + (x0 || 0)] = r[x]; });
  const legs = A.legs[frame]; put(legs, H0 - oy - legs.length);
  const pose = o.armsUp ? A.cheer : o.pose && A.pose && A.pose[o.pose];   // a pose replaces the walking torso and may reach above the shoulders
  if (pose) put(pose, 13 + bodyRows - up - pose.length); else put(A.torso[frame], 13 - up);
  const top = !o.armsUp && TOP_ART[o.top] && TOP_ART[o.top][dir]; if (top) put(top, 13 - up, top[0].length === W0 ? 0 : hx);   // overlays drawn for the big body are full width
  put(CHAR_ART[dir].head, 5 - up, hx);
  const face = FACE_ART[o.face] && FACE_ART[o.face][dir]; if (face) put(face, 12 - face.length - up, hx);                     // faces end on the lower eye row
  const hair = HAIR_ART[o.style] && HAIR_ART[o.style][dir]; if (hair) put(hair, o.style === 'bald' ? BALD_TOP - up : 13 + (HAIR_DROP[o.style] || 0) - up - hair.length, hx);
  const ARM = o.bare ? { M: 's', m: 'S', N: 'z' } : o.sleeves ? { M: 'Y', m: 'y', N: 'y' } : { M: 'C', m: 'c', N: 'd' };   // arms: bare skin, sleeves in the band colour, or the shirt
  for (const r of g) for (let x = 0; x < W0; x++) { const f = OUTFIT[r[x]]; if (f) r[x] = o[f[0]] ? f[1] : f[2]; else if (ARM[r[x]]) r[x] = ARM[r[x]]; }
  // bosses: stretch the body further by repeating a middle column and a torso row (the head keeps its size)
  const bodyTop = 13 - up + oy, mid = W0 >> 1;
  for (let i = 0; i < (o.widen || 0); i++) g.forEach((r, ri) => { if (ri >= bodyTop) { const c = [mid, mid - 1, mid + 1, mid - 2, mid + 2, mid - 3, mid + 3].find(q => r[q] !== 'k' && r[q] !== '.') ?? mid; r.splice(c, 0, r[c]); } else if (i % 2) r.push('.'); else r.unshift('.'); });
  for (let i = 0; i < (o.tall || 0); i++) g.splice(bodyTop + 4, 0, g[bodyTop + 4].slice());
  // a clear column each side, then the dark outline around everything
  for (const r of g) { r.unshift('.'); r.push('.'); }
  const W = g[0].length, H = g.length, out = g.map(r => r.slice());
  for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) {
    if (g[y][x] !== '.') continue;
    if ((y > 0 && g[y - 1][x] !== '.') || (y < H - 1 && g[y + 1][x] !== '.') || (x > 0 && g[y][x - 1] !== '.') || (x < W - 1 && g[y][x + 1] !== '.')) out[y][x] = 'k';
  }
  return out;
}
const sprCache = new Map();
function charSprite(dir, frame, o, pal) {
  const key = dir + frame + JSON.stringify(o) + JSON.stringify(pal);
  let c = sprCache.get(key); if (c) return c;
  if (sprCache.size > 900) sprCache.clear();
  const g = buildCharGrid(dir, frame, o);
  c = document.createElement('canvas'); c.width = g[0].length; c.height = g.length; const x = c.getContext('2d');
  for (let r = 0; r < g.length; r++) for (let q = 0; q < g[r].length; q++) { const ch = g[r][q]; if (ch === '.') continue; x.fillStyle = pal[ch] || '#ff00ff'; x.fillRect(q, r, 1, 1); }
  c.top = g.findIndex(r => r.some(ch => ch !== '.'));   // first row with anything in it (bars and umbrellas sit above this)
  sprCache.set(key, c); return c;
}
